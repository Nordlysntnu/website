async function as(role, id, sql, args = []) {
    await db.exec(`set role ${role}`);
    try {
        await db.query("select set_config('request.jwt.claim.sub',$1,false)", [
            id || '',
        ]);
        return await db.query(sql, args);
    } finally {
        await db.exec('reset role');
    }
}
